"""Reconstruct v0.4 text tables from existing public packets and judgments.

No packet commands, model calls, scoring, plotting, or PDF operations.
Only v0.4 analysis files and tables are written; frozen inputs remain unchanged.
"""
from __future__ import annotations

from collections import Counter
import csv
import hashlib
import json
from pathlib import Path
import re

from public_inputs import (IS_MONOREPO, PAPER, ROOT, verify_public_inputs,
                           verify_original_sources)
B = "research/cycles/2026-10-14-feedback-refinement"
SOURCES = {}


def read(path, expected=None):
    raw = (ROOT / path).read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    if expected:
        assert sha == expected, (path, "source identity changed")
    SOURCES[path] = {"path": path, "sha256": sha}
    return json.loads(raw)


def write(path, value):
    (PAPER / path).write_text(value.rstrip() + "\n", encoding="utf-8", newline="\n")


def write_json(path, value):
    write(path, json.dumps(value, ensure_ascii=False, indent=2))


def write_csv(path, rows):
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with (PAPER / path).open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows({k: json.dumps(v, ensure_ascii=False) if isinstance(v, (list, dict)) else v
                         for k, v in row.items()} for row in rows)


def business(path):
    return path.startswith(("fastapi/", "rich/", "requests/", "src/requests/",
                            "httpx/", "src/httpx/")) and path.endswith(".py")


def source_chunks(patch):
    chunks = {}
    for chunk in re.split(r"(?=^diff --git )", patch or "", flags=re.M):
        m = re.match(r"diff --git a/(.*?) b/(.*?)\n", chunk)
        if m and business(m[2]):
            chunks[m[2]] = chunk
    return chunks


def observation(event):
    try:
        return json.loads(event.get("observation", {}).get("content", "{}"))
    except (ValueError, TypeError):
        return {}


def tool(event):
    calls = event.get("tool_calls", [])
    assert len(calls) == 1
    return calls[0]


def key(r):
    return r["batch"], r["task"], r["branch"]


def summarize(coverage, phases, sources):
    summary = {}
    for name, batches in (("development", ("R01", "R02")), ("final_configuration", ("R03", "R04")),
                          ("all_configurations", ("R01", "R02", "R03", "R04"))):
        c = [r for r in coverage if r["batch"] in batches]
        response = {}
        for arm in ("control", "feedback"):
            ph = [r for r in phases if r["batch"] in batches and r["branch"] == arm]
            src = [r for r in sources if r["batch"] in batches and r["branch"] == arm]
            response[arm] = {"common_check_replay_branches": len(ph),
                             "replay_on_draft_logic": sum(r["replay_on_draft_logic"] for r in ph),
                             "replay_after_source_change": sum(r["replay_after_source_change"] for r in ph),
                             "phase_counts": dict(Counter(r["phase"] for r in ph)),
                             "source_categories": dict(Counter(r["source_category"] for r in src)),
                             "passes": sum(r["returned_status"] == "resolved" for r in src),
                             "normal_draft_pairs": sum(r["draft_status"] in ("resolved", "scored_failed") and r["returned_status"] in ("resolved", "scored_failed") for r in src),
                             "new_passes": sum(r["draft_status"] == "scored_failed" and r["returned_status"] == "resolved" for r in src),
                             "lost_passes": sum(r["draft_status"] == "resolved" and r["returned_status"] == "scored_failed" for r in src)}
        summary[name] = {"batches": batches, "task_realizations": len(c), "distinct_tasks": len({r["task"] for r in c}),
                         "coverage": dict(Counter(r["category"] for r in c)), "responses": response}
    final = summary["final_configuration"]
    assert final["coverage"] == {"no_execution_output": 23, "python_invoked_on_missing_PY_file": 38,
                                  "other_target_not_reached": 7, "peripheral_behavior": 9,
                                  "target_reached_expectation_not_grounded": 11, "supported_target_reached": 20}
    return summary


def write_tables(final):
    table = ["% Generated by scripts/build_v04_analysis.py.", "\\begin{tabular}{lr}", "\\toprule",
             "Outcome among 85 returned outputs & Count " + chr(92) * 2, "\\midrule"]
    labels = [("python_invoked_on_missing_PY_file", "Python invoked on missing \\texttt{PY} file"),
              ("other_target_not_reached", "Other failure before target behavior"),
              ("peripheral_behavior", "Related peripheral behavior only"),
              ("target_reached_expectation_not_grounded", "Target reached; expectation insufficiently grounded"),
              ("supported_target_reached", "Publicly grounded target behavior reached")]
    table += [f"{label} & {final['coverage'][code]} \\\\" for code, label in labels]
    table += ["\\bottomrule", "\\end{tabular}"]
    write("tables/construction-breakdown-v04.tex", "\n".join(table))
    c, f = final["responses"]["control"], final["responses"]["feedback"]
    rows = [("Common-check replay on draft logic", c["replay_on_draft_logic"], f["replay_on_draft_logic"]),
            ("Common-check replay after a source change", c["replay_after_source_change"], f["replay_after_source_change"]),
            ("Retained executable-source changes", c["source_categories"]["retained_executable_source_change"], f["source_categories"]["retained_executable_source_change"]),
            ("New passes from D", c["new_passes"], f["new_passes"]),
            ("Lost passes from D", c["lost_passes"], f["lost_passes"]),
            ("Final passes on the complete list", c["passes"], f["passes"])]
    table = ["% Generated by scripts/build_v04_analysis.py.", "\\begin{tabular}{lrr}", "\\toprule",
             "Branch behavior or outcome & C & F " + chr(92) * 2, "\\midrule"]
    table += [f"{label} & {a} & {b} \\\\" for label, a, b in rows]
    table += ["\\bottomrule", "\\end{tabular}"]
    write("tables/continuation-process-v04.tex", "\n".join(table))


def main():
    if not IS_MONOREPO:
        rebuild_from_derived_inputs()
        return
    phase_input = read("paper/feedback-to-fixes/evidence/check-phase-judgments-v04.json")
    reviewed = read("paper/feedback-to-fixes/evidence/revision-public-review-v03.json")
    phase_judgments = {key(r): r for r in phase_input["rows"]}
    source_judgments = {key(r): r for r in reviewed["source_branches"]}
    extra_doc = key(phase_input["additional_docstring_branch"])
    packet_rows, phases, coverage, sources, timelines, outcomes = [], [], [], [], [], []
    phase_keys = set()
    for batch in ("R01", "R02", "R03", "R04"):
        analysis = read(f"{B}/analysis-{batch}.json")
        scores = {r["task"]: r for r in analysis["tasks"]}
        freeze = read(f"{B}/behavior-freeze-{batch}.json")
        annotations = {}
        for f in freeze["files"]:
            part = read(f["path"], f["sha256"])
            annotations.update({r["instance_id"]: r for r in part["tasks"]})
        assert set(scores) == set(annotations) and len(scores) == 54
        for task, ann in sorted(annotations.items()):
            p = read(ann["packet_path"], ann["packet_sha256"])
            s = scores[task]
            packet_rows.append({"batch": batch, "task": task, "packet_path": ann["packet_path"],
                                "packet_sha256": ann["packet_sha256"]})
            for arm in ("draft", "control", "feedback"):
                patch = p["stages"][arm]["agent_patch"]
                assert patch.get("sha256") == s[arm]["patch_sha256"]
                outcomes.append({"batch": batch, "task": task, "branch": arm,
                                 "status": s[arm]["status"], "score_present": s[arm]["score_present"],
                                 "resolved": s[arm]["resolved"]})
            common = ann["common"]
            available = common["feedback_availability"]["label"] == "执行且可用"
            reach = common["target_reach"]["label"]
            support = common["public_basis_support"]["label"]
            execution = p["frozen_execution"]
            stderr = execution.get("stderr", "")
            py_filename = "can't open file" in stderr and ("/PY" in stderr or "'PY'" in stderr)
            if not available:
                category = "no_execution_output"
            elif py_filename:
                assert reach == "未触达"
                assert re.search(r"python3\s+-B\s+PY(?:\s|$)", p["frozen_check"]["command"])
                category = "python_invoked_on_missing_PY_file"
            elif reach == "未触达":
                category = "other_target_not_reached"
            elif reach == "仅相关外围":
                category = "peripheral_behavior"
            elif reach == "触达相关行为" and support != "有支持":
                category = "target_reached_expectation_not_grounded"
            else:
                assert reach == "触达相关行为" and support == "有支持"
                category = "supported_target_reached"
            coverage.append({"batch": batch, "task": task, "output_available": available,
                             "category": category, "public_basis_label": support, "target_reach_label": reach,
                             "execution_semantics": common["execution_semantics"]["label"],
                             "command_first_line": p["frozen_check"].get("command", "").split("\n")[0],
                             "stderr_excerpt": stderr[:450], "packet_path": ann["packet_path"]})
            d_chunks = source_chunks(p["stages"]["draft"]["agent_patch"].get("text"))
            for arm in ("control", "feedback"):
                k = (batch, task, arm)
                branch = ann["branches"][arm]
                events = p["stages"][arm]["official_tool_events"]["events"]
                changed = d_chunks != source_chunks(p["stages"][arm]["agent_patch"].get("text"))
                prior = source_judgments.get(k)
                if prior and prior["category"] not in ("docstring_only", "temporary_edit_restored"):
                    assert changed
                    source_category = "retained_executable_source_change"
                elif (prior and prior["category"] == "docstring_only") or k == extra_doc:
                    assert changed
                    source_category = "docstring_only"
                elif prior:
                    assert prior["category"] == "temporary_edit_restored" and not changed
                    source_category = "temporary_source_edit_restored"
                else:
                    assert not changed, (k, "unreviewed returned source change")
                    source_category = "no_recorded_executable_source_change"
                # Reconcile successful source-file tool writes outside the reviewed set.
                if not prior and k != extra_doc:
                    for e in events:
                        for t in e.get("tool_calls", []):
                            a = t.get("arguments", {})
                            assert not (t["function_name"] in ("edit_file", "write_file")
                                        and business(a.get("filepath", a.get("path", "")))
                                        and observation(e).get("status") == "ok"), (k, "source write outside review")
                sources.append({"batch": batch, "task": task, "branch": arm,
                                "original_source_label": branch["actual_modification"]["label"],
                                "source_category": source_category, "source_file_patch_changed": changed,
                                "original_v03_category": prior["category"] if prior else None,
                                "draft_status": s["draft"]["status"], "returned_status": s[arm]["status"],
                                "draft_patch_sha256": s["draft"]["patch_sha256"],
                                "returned_patch_sha256": s[arm]["patch_sha256"], "packet_path": ann["packet_path"]})
                if branch["feedback_reacquisition"]["label"] == "同检重新执行":
                    j = phase_judgments.get(k)
                    if branch["actual_modification"]["label"] == "源码已修改":
                        assert j is not None, k
                    if j:
                        phase_keys.add(k)
                        for i in j["source_edit_events"] + j.get("docstring_events", []):
                            assert tool(events[i])["function_name"] in ("edit_file", "write_file", "run_command")
                            assert observation(events[i]).get("status") == "ok"
                        for i in j["draft_check_events"] + j["revised_check_events"]:
                            assert tool(events[i])["function_name"] == "run_command"
                            assert "BudgetExceeded" not in events[i].get("observation", {}).get("content", "")
                            if j["source_edit_events"]:
                                assert (i < min(j["source_edit_events"])) == (i in j["draft_check_events"])
                        before, after = bool(j["draft_check_events"]), bool(j["revised_check_events"])
                    else:
                        before, after = True, False
                    phases.append({"batch": batch, "task": task, "branch": arm,
                                   "replay_on_draft_logic": before, "replay_after_source_change": after,
                                   "phase": "both" if before and after else "draft_only" if before else "revised_only",
                                   "review_basis": "direct_event_review" if j else "frozen_action_label_and_source_reconciliation",
                                   "draft_check_events": j["draft_check_events"] if j else [],
                                   "revised_check_events": j["revised_check_events"] if j else [],
                                   "original_replay_evidence": branch["feedback_reacquisition"],
                                   "phase_note": j["note"] if j else "No executable source edit recorded; replay is at D's executable state.",
                                   "packet_path": ann["packet_path"], "packet_sha256": ann["packet_sha256"]})
            if (batch, task) in {(r["batch"], r["task"]) for r in reviewed["budget_rejected_feedback_edit_slots"]}:
                events = p["stages"]["feedback"]["official_tool_events"]["events"]
                first = next(i for i, e in enumerate(events)
                             if tool(e)["function_name"] in ("edit_file", "write_file")
                             and business(tool(e).get("arguments", {}).get("filepath", "")))
                assert "BudgetExceeded" in events[first]["observation"]["content"]
                spent = []
                for i, e in enumerate(events[:first]):
                    t = tool(e)
                    if t["function_name"] not in ("read_file", "run_command"):
                        continue
                    if "BudgetExceeded" in e.get("observation", {}).get("content", ""):
                        continue
                    cmd = t.get("arguments", {}).get("command", "")
                    category = "read" if t["function_name"] == "read_file" else "search" if cmd.lstrip().startswith("grep ") else "execution"
                    spent.append({"event": i, "tool": t["function_name"], "category": category,
                                  "arguments": t.get("arguments", {}), "elapsed_seconds": t.get("extra", {}).get("elapsed_s")})
                assert len(spent) == 8, (batch, task, len(spent))
                elapsed = tool(events[first])["extra"]["elapsed_s"]
                assert s["draft"]["patch_sha256"] == s["feedback"]["patch_sha256"]
                timelines.append({"batch": batch, "task": task, "first_source_edit_event": first,
                                  "first_source_edit_seconds": elapsed, "nominal_seconds_remaining": 150 - elapsed,
                                  "spent_opportunities": dict(Counter(e["category"] for e in spent)),
                                  "eight_spent_events": spent, "delivered_equals_draft": True,
                                  "packet_path": ann["packet_path"]})
    assert phase_keys == set(phase_judgments) and len(phases) == 155
    assert len(packet_rows) == 216 and len(sources) == 432 and len(outcomes) == 648
    summary = summarize(coverage, phases, sources)
    final = summary["final_configuration"]
    write_csv("supplement/check-phases-v04.csv", phases)
    write_csv("supplement/check-construction-v04.csv", coverage)
    write_csv("supplement/source-delivery-v04.csv", sources)
    write_csv("supplement/edit-opportunities-v04.csv", timelines)
    write_json("evidence/process-analysis-v04.json", {
        "version": "v0.4", "date_beijing": "2026-11-10", "timing": "Post-hoc analysis of existing public records; original annotations and scores retained.",
        "phase_definition": phase_input["event_index"], "summary": summary, "phase_review": phase_input,
        "budget_timelines": timelines, "packet_identity_checks": packet_rows,
        "accounting": dict(Counter(r["status"] for r in outcomes)), "sources": list(SOURCES.values())})
    write_tables(final)
    print(json.dumps({"packets": len(packet_rows), "phase_rows": len(phases), "source_rows": len(sources), "summary": summary}, ensure_ascii=False, indent=2))


def rebuild_from_derived_inputs():
    verified_inputs = verify_public_inputs()
    original = json.loads((PAPER / "evidence/process-analysis-v04.json").read_bytes())
    provenance = verify_original_sources(original["sources"])

    def rows(name):
        with (PAPER / name).open(encoding="utf-8", newline="") as stream:
            return list(csv.DictReader(stream))

    coverage = rows("supplement/check-construction-v04.csv")
    sources = rows("supplement/source-delivery-v04.csv")
    phases = rows("supplement/check-phases-v04.csv")
    for row in phases:
        for field in ("replay_on_draft_logic", "replay_after_source_change"):
            assert row[field] in ("True", "False")
            row[field] = row[field] == "True"
    assert len(coverage) == len({(r["batch"], r["task"]) for r in coverage}) == 216
    assert len(sources) == len({key(r) for r in sources}) == 432
    assert len(phases) == len({key(r) for r in phases}) == 155
    for batch in ("R01", "R02", "R03", "R04"):
        assert sum(r["batch"] == batch for r in coverage) == 54
    summary = summarize(coverage, phases, sources)
    assert json.loads(json.dumps(summary)) == original["summary"], "Derived summary changed"
    indexed = {key(r): r for r in sources}
    identities = {(r["batch"], r["task"]): r for r in original["packet_identity_checks"]}
    assert len(identities) == 216
    outcomes = []
    for row in coverage:
        k = (row["batch"], row["task"])
        c, f = indexed[k + ("control",)], indexed[k + ("feedback",)]
        assert c["draft_status"] == f["draft_status"]
        assert c["draft_patch_sha256"] == f["draft_patch_sha256"]
        assert row["packet_path"] == c["packet_path"] == f["packet_path"] == identities[k]["packet_path"]
        outcomes.extend((c["draft_status"], c["returned_status"], f["returned_status"]))
    assert dict(Counter(outcomes)) == original["accounting"]
    for row in phases:
        identity = identities[(row["batch"], row["task"])]
        assert (row["packet_path"], row["packet_sha256"]) == (identity["packet_path"], identity["packet_sha256"])
    timelines = rows("supplement/edit-opportunities-v04.csv")
    assert len(timelines) == len(original["budget_timelines"]) == 4
    for row, frozen in zip(timelines, original["budget_timelines"]):
        for field, value in frozen.items():
            actual = json.loads(row[field]) if isinstance(value, (dict, list)) else (
                row[field] == "True" if isinstance(value, bool) else
                type(value)(row[field]) if isinstance(value, (int, float)) else row[field])
            assert actual == value, (field, "Frozen timeline changed")
    # Re-emit the verified aggregate and tables; this mode never extracts absent packets.
    write_json("evidence/process-analysis-v04.json", original)
    write_tables(summary["final_configuration"])
    print(json.dumps({"mode": "lightweight-derived-inputs", "full_packet_extraction": False,
                      "verified_bundled_inputs": verified_inputs, "original_provenance": provenance,
                      "realizations": len(coverage), "source_rows": len(sources),
                      "phase_rows": len(phases), "endpoints": len(outcomes)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
